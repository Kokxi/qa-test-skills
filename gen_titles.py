def first_person_excuse(title, explanation):
    """Generic first-person excuse transformation"""
    # Pattern matching rules
    t = title
    e = explanation
    
    # Rule: "忽略XXX" or "XXX忽略"
    if t.startswith("忽略"):
        action = t[2:]
        return f"{action}不重要，不用管"
    
    # Rule: "不XXX" / "XXX不YYY"
    if t.startswith("不"):
        return f"为什么要{t}？没必要"
    
    # Rule: "只XXX" / "只看XXX"
    if t.startswith("只"):
        return f"{t}就够了"
    
    # Rule: "XXX缺失" / "缺少XXX"
    if "缺失" in t or "缺少" in t or "缺" in t:
        return f"缺少{t.replace('缺失','').replace('缺少','').replace('缺','')}不影响"
    
    # Rule: "XXX不够" / "XXX不足"
    if "不够" in t or "不足" in t:
        return f"{t.replace('不够','').replace('不足','')}差不多就行了"
    
    # Rule: "XXX不当" / "不会XXX" / "不XXX"
    if "不当" in t or "错误" in t or "不准" in t:
        return f"{t}？我觉得没问题"
    
    # Rule: "忘记XXX"
    if t.startswith("忘记"):
        return f"{t[2:]}太麻烦，不做了"
    
    # Rule: "XX无用" / "XX没用"
    if "无用" in t or "没用" in t:
        return f"{t.replace('无用','').replace('没用','')}做了也没用"
    
    # Rule: sentences with "只看" / "只做" etc
    if "只" in t:
        return f"{t}就够了，想那么复杂干嘛"
    
    # Default: use explanation to make an excuse
    return f"{title}？这不是常规操作吗"

